/**
 * Все строки интерфейса на двух языках. В JSX текст не пишем, только dict.*.
 * Язык берётся из адреса (/ru/..., /kk/...), поэтому ссылку можно отправить
 * и она откроется на нужном языке.
 */

export const locales = ["ru", "kk"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "ru";

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value);
}

/** Подставляет значения в шаблон: t("{n} класс", { n: 2 }) → "2 класс". */
export function t(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

