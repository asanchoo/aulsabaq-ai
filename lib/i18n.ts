/** «19 ноября», «19 қараша». Не Intl: в Chrome нет казахских названий месяцев, и выходило «М11 19». */
export function formatDay(date: Date | number, lang: Locale): string {
  const d = new Date(date);
  return `${d.getDate()} ${MONTHS[lang][d.getMonth()]}`;
}

export function t(
  template: string,
  vars: Record<string, string | number>,
): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    String(vars[key] ?? `{${key}}`),
  );
}

